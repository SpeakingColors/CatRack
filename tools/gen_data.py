#!/usr/bin/env python3
"""Turn docs/mockup/data.json (tools/dump_data.py) into src/core/UnitData.h (unit and control tables) and
src/editor/FactoryData.h (the factory chains). The tables are the mockup's own, so plugin and mockup cannot drift."""
import json
d = json.load(open('docs/mockup/data.json'))
HOSTED = None   # None: the first 20 of the mockup order plus the keys listed in EXTRA
EXTRA = ['shm', 'sdl', 'hbl', 'scr']      # keys of the later units that are hosted in this build (edited per batch)
def q(s): return json.dumps(s, ensure_ascii=False)
def f(x): return repr(float(x)) + 'f'
out = ['// GENERATED by tools/gen_data.py from docs/mockup/CatRack.html. Do not edit by hand.', '#pragma once', '#include <cstdint>', 'namespace catr {',
       'constexpr int kNumUnits = %d;' % len(d['order']), 'constexpr int kMaxParams = 18;',
       'enum Viz { VizGr = 0, VizEq = 1, VizWet = 2 };',
       'struct ParamDef { const char* id; const char* label; const char* shortLabel; const char* longLabel; float mn, mx, def; const char* unit; int dec; const char* tip; bool logScale; int nNames; const char* names[12]; const char* sn[12]; };',
       'struct UnitDef { const char* key; const char* name; const char* code; const char* kind; const char* cat; const char* src; const char* blurb; uint32_t color; int viz; bool analyser; int nParams; ParamDef p[18]; };',
       'inline const UnitDef* unitTable()', '{', '    static const UnitDef t[kNumUnits] = {']
for k in d['order']:
    u = d['units'][k]
    ps = []
    for p in u['params']:
        names = p['names'] or []
        sn = p['sn'] or []
        pad = lambda a: ', '.join([q(x) for x in a] + ['""'] * (12 - len(a)))
        ps.append('{ %s, %s, %s, %s, %s, %s, %s, %s, %d, %s, %s, %d, { %s }, { %s } }' % (
            q(p['id']), q(p['l']), q(p['s']), q(p['kl'] or p['l']), f(p['min']), f(p['max']), f(p['def']), q(p['u']), p['d'], q(p['tip']),
            'true' if p['log'] else 'false', len(names), pad(names[:12]), pad(sn[:12])))
    vz = {'gr': 'VizGr', 'eq': 'VizEq', 'wet': 'VizWet'}[u['vz']]
    out.append('        { %s, %s, %s, %s, %s, %s, %s, 0xff%s, %s, %s, %d, {\n            %s } },' % (
        q(k), q(u['name']), q(u['code']), q(u['kind']), q(u['cat']), q(u['src']), q(u['blurb']), u['color'][1:], vz,
        'true' if u['ana'] else 'false', len(ps), ',\n            '.join(ps)))
hosted = [1 if (i < 20 or k in EXTRA) else 0 for i, k in enumerate(d['order'])]
out += ['    };', '    return t;', '}',
        'constexpr bool kHostedTable[kNumUnits] = { %s };' % ', '.join('true' if h else 'false' for h in hosted),
        'inline bool hosted(int t) { return t >= 0 && t < kNumUnits && kHostedTable[t]; }',
        'constexpr int kBuiltUnits = %d;   // how many are hosted' % sum(hosted),
        '} // namespace catr', '']
open('src/core/UnitData.h', 'w').write('\n'.join(out))

# factory chains: only the ones whose units are all hosted in this build
keys = [k for i, k in enumerate(d['order']) if hosted[i]]
pres = []
for p in d['factory']:
    us = []
    for c in p['chain']:
        if isinstance(c, dict): us += [a[0] for a in c['par']]
        else: us.append(c[0])
    if all(u in keys for u in us): pres.append(p)
js = []
for p in pres:
    chain = []
    for c in p['chain']:
        if isinstance(c, dict): chain.append({'par': [[a[0], a[1]] for a in c['par']], 'mix': c.get('mix', 100)})
        else: chain.append({'u': c[0], 'o': c[1]})
    js.append(json.dumps({'name': p['name'], 'type': p['type'], 'desc': p['desc'], 'chain': chain}, ensure_ascii=False))
o2 = ['// GENERATED by tools/gen_data.py from the mockup factory chains (those whose units are all hosted). Do not edit by hand.', '#pragma once',
      'namespace catr {', 'inline const char* const* factoryChainsJson(int& n)', '{', '    static const char* const t[] = {']
o2 += ['        R"JSON(%s)JSON",' % j for j in js]
o2 += ['    };', '    n = %d;' % len(js), '    return t;', '}', '} // namespace catr', '']
open('src/editor/FactoryData.h', 'w').write('\n'.join(o2))
print(len(pres), 'factory chains')
